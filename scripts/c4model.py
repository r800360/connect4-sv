"""Connect 4 reference model and a search for short games whose first win is of a requested kind."""
import random

ROWS, COLS = 6, 7


def windows():
    w = []
    for c in range(COLS):
        for r in range(ROWS):
            if c + 3 < COLS:
                w.append(("H", [(c + i, r) for i in range(4)]))
            if r + 3 < ROWS:
                w.append(("V", [(c, r + i) for i in range(4)]))
            if c + 3 < COLS and r + 3 < ROWS:
                w.append(("D/", [(c + i, r + i) for i in range(4)]))
            if c + 3 < COLS and r - 3 >= 0:
                w.append(("D\\", [(c + i, r - i) for i in range(4)]))
    return w


WINDOWS = windows()
assert len(WINDOWS) == 69


class Game:
    def __init__(self):
        self.board = [[0] * ROWS for _ in range(COLS)]
        self.h = [0] * COLS
        self.turn, self.winner, self.moves, self.win_windows = 1, 0, 0, []

    def press(self, k):                       # k = 1..7
        c = k - 1
        if self.winner or self.h[c] == ROWS:
            return False
        self.board[c][self.h[c]] = self.turn
        self.h[c] += 1
        self.moves += 1
        wins = [(kind, cells) for kind, cells in WINDOWS if all(self.board[x][y] == self.turn for x, y in cells)]
        if wins:
            self.winner, self.win_windows = self.turn, wins
        self.turn = 3 - self.turn
        return True


def find(pred, seed=1, tries=200000):
    """shortest random legal game (up to its first win) whose win satisfies pred(game)."""
    rnd = random.Random(seed)
    best = None
    for _ in range(tries):
        g, seq = Game(), ""
        while not g.winner and g.moves < 42:
            k = rnd.randrange(1, 8)
            if g.press(k):
                seq += str(k)
            if best and len(seq) >= len(best):
                break
        if g.winner and pred(g) and (best is None or len(seq) < len(best)):
            best = seq
    return best


if __name__ == "__main__":
    import sys
    specs = [
        ("red vertical win, rows 1-4", lambda g: g.winner == 1 and any(k == "V" and c[0][1] == 0 for k, c in g.win_windows)),
        ("yellow vertical win, rows 1-4", lambda g: g.winner == 2 and any(k == "V" and c[0][1] == 0 for k, c in g.win_windows)),
        ("red vertical win, rows 2-5", lambda g: g.winner == 1 and any(k == "V" and c[0][1] == 1 for k, c in g.win_windows)),
        ("yellow vertical win, rows 2-5", lambda g: g.winner == 2 and any(k == "V" and c[0][1] == 1 for k, c in g.win_windows)),
        ("red vertical win, rows 3-6", lambda g: g.winner == 1 and any(k == "V" and c[0][1] == 2 for k, c in g.win_windows)),
        ("yellow vertical win, rows 3-6", lambda g: g.winner == 2 and any(k == "V" and c[0][1] == 2 for k, c in g.win_windows)),
        ("red horizontal win, bottom row", lambda g: g.winner == 1 and any(k == "H" and c[0][1] == 0 for k, c in g.win_windows)),
        ("yellow horizontal win, bottom row", lambda g: g.winner == 2 and any(k == "H" and c[0][1] == 0 for k, c in g.win_windows)),
        ("horizontal win in row 4 or higher", lambda g: any(k == "H" and c[0][1] >= 3 for k, c in g.win_windows)),
        ("red diagonal win (rising, up-right)", lambda g: g.winner == 1 and any(k == "D/" for k, c in g.win_windows)),
        ("yellow diagonal win (rising, up-right)", lambda g: g.winner == 2 and any(k == "D/" for k, c in g.win_windows)),
        ("red diagonal win (falling, down-right)", lambda g: g.winner == 1 and any(k == "D\\" for k, c in g.win_windows)),
        ("yellow diagonal win (falling, down-right)", lambda g: g.winner == 2 and any(k == "D\\" for k, c in g.win_windows)),
    ]
    out = ["// generated by scripts/c4model.py: shortest random games whose FIRST win is of the named kind"]
    for i, (name, pred) in enumerate(specs):
        seq = find(pred, seed=i + 1)
        g = Game()
        for ch in seq:
            g.press(int(ch))
        assert g.winner and pred(g), name
        out.append(f'    new_game(); play("{seq}", "{name}"); group("CORE", "{name} ({len(seq)} moves: {seq})");')
        print(f"{name:36s} {seq}")
    open(sys.argv[1], "w", newline="\n").write("\n".join(out) + "\n")


def find_draw(seed=7, tries=500000):
    rnd = random.Random(seed)
    for _ in range(tries):
        g, seq = Game(), ""
        while not g.winner and g.moves < 42:
            k = rnd.randrange(1, 8)
            if g.press(k):
                seq += str(k)
        if not g.winner and g.moves == 42:
            return seq
    return None
